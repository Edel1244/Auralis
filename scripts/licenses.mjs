#!/usr/bin/env node
/**
 * Generates THIRD_PARTY_LICENSES.md from installed dependencies and flags any
 * license that is not on the AGPL-3.0-compatible allow-list.
 *
 *   node scripts/licenses.mjs            # write the file
 *   node scripts/licenses.mjs --check    # exit 1 if an unknown/incompatible license is found
 */
import { readFileSync, writeFileSync, readdirSync, existsSync } from "node:fs";
import path from "node:path";

const root = process.cwd();
const pkg = JSON.parse(readFileSync(path.join(root, "package.json"), "utf8"));
const ALLOWED = new Set(["MIT", "ISC", "Apache-2.0", "BSD-2-Clause", "BSD-3-Clause", "0BSD", "BlueOak-1.0.0", "CC0-1.0", "Unlicense", "Python-2.0", "MPL-2.0", "CC-BY-4.0", "LGPL-3.0-or-later", "Zlib", "WTFPL", "MIT-0"]);

function readPkg(dir) {
  const f = path.join(dir, "package.json");
  return existsSync(f) ? JSON.parse(readFileSync(f, "utf8")) : null;
}
function license(p) {
  if (!p) return "UNKNOWN";
  if (typeof p.license === "string") return p.license;
  if (p.license?.type) return p.license.type;
  if (Array.isArray(p.licenses)) return p.licenses.map((l) => l.type ?? l).join(" OR ");
  return "UNKNOWN";
}
const isAllowed = (expr) =>
  expr
    .replace(/[()]/g, "")
    .split(/\s+(?:OR|AND)\s+/)
    .some((id) => ALLOWED.has(id.trim()));

// All installed packages (transitive), to catch anything shipped in builds.
const all = new Map();
function scan(nm) {
  if (!existsSync(nm)) return;
  for (const name of readdirSync(nm)) {
    if (name.startsWith(".")) continue;
    const full = path.join(nm, name);
    if (name.startsWith("@")) {
      for (const sub of readdirSync(full)) visit(path.join(full, sub), `${name}/${sub}`);
    } else visit(full, name);
  }
}
function visit(dir, name) {
  const p = readPkg(dir);
  if (!p) return;
  const key = `${name}@${p.version}`;
  if (!all.has(key)) all.set(key, { name, version: p.version, license: license(p), homepage: p.homepage ?? (typeof p.repository === "string" ? p.repository : p.repository?.url) ?? "" });
  scan(path.join(dir, "node_modules"));
}
scan(path.join(root, "node_modules"));

const direct = (deps, kind) =>
  Object.keys(deps ?? {}).sort().map((name) => {
    const p = readPkg(path.join(root, "node_modules", name));
    return `| [${name}](https://www.npmjs.com/package/${name}) | ${p?.version ?? "?"} | ${license(p)} | ${kind} |`;
  });

const counts = {};
for (const d of all.values()) counts[d.license] = (counts[d.license] ?? 0) + 1;
const flagged = [...all.values()].filter((d) => !isAllowed(d.license));

const md = `# Third-party licenses

AURALIS is licensed under **AGPL-3.0-only** (see [LICENSE](LICENSE)). It is built on the open-source
packages below. This file is generated by \`node scripts/licenses.mjs\`; do not edit it by hand.

## Direct dependencies

| Package | Version | License | Type |
|---|---|---|---|
${[...direct(pkg.dependencies, "runtime"), ...direct(pkg.devDependencies, "development")].join("\n")}

## All installed packages by license (${all.size} packages, including transitive)

| License | Packages |
|---|---|
${Object.entries(counts).sort((a, b) => b[1] - a[1]).map(([l, n]) => `| ${l} | ${n} |`).join("\n")}

${flagged.length ? `## Needs review\n\n${flagged.map((d) => `- ${d.name}@${d.version}: ${d.license}`).join("\n")}\n` : "All licenses are on the AGPL-3.0-compatible allow-list.\n"}
## External services

AURALIS does **not** depend on any proprietary music streaming service. Optional integrations:
- Any SMTP server (email), any S3-compatible object storage (MinIO, Garage, Ceph, AWS S3, Cloudflare R2…).
- Fonts (Inter, Sora; SIL Open Font License 1.1) are downloaded at build time by \`next/font\` and self-hosted.
`;

if (process.argv.includes("--check")) {
  if (flagged.length) {
    console.error("Licenses needing review:\n" + flagged.map((d) => `  ${d.name}@${d.version}: ${d.license}`).join("\n"));
    process.exit(1);
  }
  console.log(`OK: ${all.size} packages, all licenses allowed.`);
} else {
  writeFileSync(path.join(root, "THIRD_PARTY_LICENSES.md"), md);
  console.log(`Wrote THIRD_PARTY_LICENSES.md (${all.size} packages, ${flagged.length} need review).`);
  if (flagged.length) console.log(flagged.map((d) => `  ${d.name}@${d.version}: ${d.license}`).join("\n"));
}
